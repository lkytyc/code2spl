import csv

class CSVProcessor:
    def read_csv(self, filename):
        with open(filename, 'r', newline='', encoding='utf-8') as f:
            reader = csv.reader(f)
            rows = list(reader)
        if not rows:
            return [], []
        return rows[0], rows[1:]

    def write_csv(self, filename, rows):
        try:
            with open(filename, 'w', newline='', encoding='utf-8') as f:
                writer = csv.writer(f)
                writer.writerows(rows)
            return 1
        except Exception:
            return 0

    def process(self, column_index, input_filename):
        header, rows = self.read_csv(input_filename)
        if column_index < 0 or column_index >= len(header):
            return 0

        output_filename = self._output_filename(input_filename)
        output_rows = [[header[column_index]]]
        output_rows.extend([row[column_index].upper()] for row in rows)
        return self.write_csv(output_filename, output_rows)

    def _output_filename(self, input_filename):
        if input_filename.lower().endswith('.csv'):
            return input_filename[:-4] + '_process.csv'
        return input_filename + '_process.csv'

import unittest
import os

class CSVProcessorTestWriteCSV(unittest.TestCase):
    def test_write_csv_1(self):
        self.file = 'read_test.csv'

        file_path = self.file
        csvProcessor = CSVProcessor()
        data = [['a', 'b', 'c', 'd'], ['1', '2', '3', '4']]
        # assert return value
        self.assertEqual(1, csvProcessor.write_csv(data, file_path))

        # read to test if write correctly
        read_title, read_data = csvProcessor.read_csv(file_path)
        self.assertEqual(read_title, data[0])
        self.assertEqual(read_data[0], data[1])
        os.remove(file_path)

