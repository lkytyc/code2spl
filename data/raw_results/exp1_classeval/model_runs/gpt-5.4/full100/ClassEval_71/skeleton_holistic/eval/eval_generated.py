class PushBoxGame:
    """
    This class implements a functionality of a sokoban game, where the player needs to move boxes to designated targets in order to win.
    """

    def __init__(self, map):
        """
        Initialize the push box game with the map and various attributes.
        :param map: list[str], the map of the push box game, represented as a list of strings. 
            Each character on the map represents a different element, including the following:
            - '#' represents a wall that neither the player nor the box can pass through;
            - 'O' represents the initial position of the player;
            - 'G' represents the target position;
            - 'X' represents the initial position of the box.
        >>> map = ["#####", "#O  #", "# X #", "#  G#", "#####"]   
        >>> game = PushBoxGame(map)                
        """
        self.map = map
        self.player_row = 0
        self.player_col = 0
        self.targets = []
        self.boxes = []
        self.target_count = 0
        self.is_game_over = False
        self.init_game()

    def init_game(self):
        """
        Initialize the game by setting the positions of the player, targets, and boxes based on the map.
        >>> game = PushBoxGame(["#####", "#O  #", "# X #", "#  G#", "#####"]) 
        >>> game.targets
        [(3, 3)]
        >>> game.boxes
        [(2, 2)]
        >>> game.player_row
        1
        >>> game.player_col
        1
        """
        self.targets = []
        self.boxes = []
        self.target_count = 0
        for r, row in enumerate(self.map):
            for c, ch in enumerate(row):
                if ch == 'O':
                    self.player_row = r
                    self.player_col = c
                elif ch == 'G':
                    self.targets.append((r, c))
                    self.target_count += 1
                elif ch == 'X':
                    self.boxes.append((r, c))

    def check_win(self):
        """
        Check if the game is won. The game is won when all the boxes are placed on target positions.
        And update the value of self.is_game_over.
        :return self.is_game_over: True if all the boxes are placed on target positions, or False otherwise.
        >>> game = PushBoxGame(["#####", "#O  #", "# X #", "#  G#", "#####"]) 
        >>> game.check_win()
        """
        self.is_game_over = all(box in self.targets for box in self.boxes) and len(self.boxes) == self.target_count
        return self.is_game_over

    def move(self, direction):
        """
        Move the player based on the specified direction and check if the game is won.
        :param direction: str, the direction of the player's movement. 
            It can be 'w', 's', 'a', or 'd' representing up, down, left, or right respectively.

        :return: True if the game is won, False otherwise.
        >>> game = PushBoxGame(["#####", "#O  #", "# X #", "#  G#", "#####"])       
        >>> game.print_map()
        # # # # # 
        # O     #
        #   X   #
        #     G #
        # # # # #
        >>> game.move('d')
        False
        >>> game.move('s')   
        False
        >>> game.move('a')   
        False
        >>> game.move('s') 
        False
        >>> game.move('d') 
        True
        """
        if self.is_game_over:
            return True

        dr, dc = 0, 0
        if direction == 'w':
            dr = -1
        elif direction == 's':
            dr = 1
        elif direction == 'a':
            dc = -1
        elif direction == 'd':
            dc = 1
        else:
            return self.check_win()

        nr = self.player_row + dr
        nc = self.player_col + dc
        if nr < 0 or nr >= len(self.map) or nc < 0 or nc >= len(self.map[nr]):
            return self.check_win()
        if self.map[nr][nc] == '#':
            return self.check_win()

        if (nr, nc) in self.boxes:
            br = nr + dr
            bc = nc + dc
            if br < 0 or br >= len(self.map) or bc < 0 or bc >= len(self.map[br]):
                return self.check_win()
            if self.map[br][bc] == '#' or (br, bc) in self.boxes:
                return self.check_win()
            idx = self.boxes.index((nr, nc))
            self.boxes[idx] = (br, bc)

        self.player_row = nr
        self.player_col = nc
        return self.check_win()

    def print_map(self):
        rendered = []
        for r, row in enumerate(self.map):
            chars = list(row)
            for c, ch in enumerate(chars):
                if ch == ' ':
                    chars[c] = ' '
            for tr, tc in self.targets:
                if r == tr and tc < len(chars) and chars[tc] == ' ':
                    chars[tc] = 'G'
            for br, bc in self.boxes:
                if r == br and bc < len(chars):
                    chars[bc] = 'X'
            if r == self.player_row and self.player_col < len(chars):
                chars[self.player_col] = 'O'
            rendered.append(' '.join(chars))
        for line in rendered:
            print(line)

