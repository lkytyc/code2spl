class AccessGatewayFilter:
    def __init__(self):
        pass

    def filter(self, request):
        path = request.get('path', '')
        method = request.get('method', '')
        headers = request.get('headers', {})

        if self._is_path_allowed(path):
            return True

        try:
            token = self._extract_token(headers)
            if token is None:
                return False

            payload = self._decode_token(token)
            if payload is None:
                return False

            if not self._is_token_valid(payload):
                return False

            level = payload.get('level', 0)
            if level > 2:
                name = payload.get('name', 'unknown')
                address = payload.get('address', 'unknown')
                current_time = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
                print(f"User: {name}, Address: {address}, Time: {current_time}")
                return True

            return False
        except Exception:
            return False

    def _is_path_allowed(self, path):
        return path.startswith('/api') or path.startswith('/login')

    def _extract_token(self, headers):
        auth_header = headers.get('Authorization', '')
        if not auth_header:
            return None

        parts = auth_header.split(' ')
        if len(parts) != 2 or parts[0].lower() != 'bearer':
            return None

        return parts[1]

    def _decode_token(self, token):
        try:
            parts = token.split('.')
            if len(parts) != 3:
                return None

            payload_part = parts[1]
            payload_part += '=' * (-len(payload_part) % 4)
            payload_bytes = base64.urlsafe_b64decode(payload_part)
            payload = json.loads(payload_bytes.decode('utf-8'))
            return payload
        except Exception:
            return None

    def _is_token_valid(self, payload):
        if 'exp' not in payload:
            return False

        try:
            exp = payload['exp']
            if isinstance(exp, (int, float)):
                exp_time = datetime.datetime.fromtimestamp(exp)
            else:
                exp_time = datetime.datetime.fromisoformat(exp)

            now = datetime.datetime.now()
            if exp_time < now:
                return False

            if 'iat' in payload:
                iat = payload['iat']
                if isinstance(iat, (int, float)):
                    iat_time = datetime.datetime.fromtimestamp(iat)
                else:
                    iat_time = datetime.datetime.fromisoformat(iat)

                if (now - iat_time).days > 3:
                    return False

            return True
        except Exception:
            return False

