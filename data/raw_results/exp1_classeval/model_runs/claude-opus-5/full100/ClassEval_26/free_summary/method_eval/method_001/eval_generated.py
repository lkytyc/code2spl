import csv


class CSVProcessor:

    def read_csv(self, file_path):
        with open(file_path, 'r', newline='') as f:
            reader = csv.reader(f)
            rows = list(reader)
        title = rows[0] if rows else []
        data = rows[1:] if len(rows) > 1 else []
        return title, data

    def write_csv(self, file_path, rows):
        try:
            with open(file_path, 'w', newline='') as f:
                writer = csv.writer(f)
                writer.writerows(rows)
            return 1
        except:
            return 0

    def process_csv_data(self, file_path, n):
        title, data = self.read_csv(file_path)
        column_values = [row[n].upper() for row in data]
        base = file_path.split('.')[0]
        ext = '.' + file_path.split('.')[1] if '.' in file_path else ''
        output_path = base + '_process' + ext
        self.write_csv(output_path, [title, column_values])

import unittest
import os

class CSVProcessorTestWriteCSV(unittest.TestCase):
    def test_write_csv_1(self):
        self.file = 'read_test.csv'

        file_path = self.file
        csvProcessor = CSVProcessor()
        data = [['a', 'b', 'c', 'd'], ['1', '2', '3', '4']]
        # assert return value
        self.assertEqual(1, csvProcessor.write_csv(data, file_path))

        # read to test if write correctly
        read_title, read_data = csvProcessor.read_csv(file_path)
        self.assertEqual(read_title, data[0])
        self.assertEqual(read_data[0], data[1])
        os.remove(file_path)

