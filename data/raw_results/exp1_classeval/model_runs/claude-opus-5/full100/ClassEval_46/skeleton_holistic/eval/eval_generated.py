class Interpolation:
    """
    This is a class that implements the Linear interpolation operation of one-dimensional and two-dimensional data
    """

    def __init__(self):
        pass

    @staticmethod
    def interpolate_1d(x, y, x_interp):
        """
        Linear interpolation of one-dimensional data
        :param x: The x-coordinate of the data point, list.
        :param y: The y-coordinate of the data point, list.
        :param x_interp: The x-coordinate of the interpolation point, list.
        :return: The y-coordinate of the interpolation point, list.
        >>> interpolation = Interpolation()
        >>> interpolation.interpolate_1d([1, 2, 3], [1, 2, 3], [1.5, 2.5])
        [1.5, 2.5]

        """
        y_interp = []
        for xi in x_interp:
            # Find the interval [x[i], x[i+1]] that contains xi
            for i in range(len(x) - 1):
                if x[i] <= xi <= x[i + 1]:
                    # Linear interpolation formula
                    t = (xi - x[i]) / (x[i + 1] - x[i])
                    yi = y[i] + t * (y[i + 1] - y[i])
                    y_interp.append(yi)
                    break
        return y_interp

    @staticmethod
    def interpolate_2d(x, y, z, x_interp, y_interp):
        """
        Linear interpolation of two-dimensional data
        :param x: The x-coordinate of the data point, list.
        :param y: The y-coordinate of the data point, list.
        :param z: The z-coordinate of the data point, list.
        :param x_interp: The x-coordinate of the interpolation point, list.
        :param y_interp: The y-coordinate of the interpolation point, list.
        :return: The z-coordinate of the interpolation point, list.
        >>> interpolation = Interpolation()
        >>> interpolation.interpolate_2d([1, 2, 3], [1, 2, 3], [[1, 2, 3], [4, 5, 6], [7, 8, 9]], [1.5, 2.5], [1.5, 2.5])
        [3.0, 7.0]

        """
        z_interp = []
        for xi, yi in zip(x_interp, y_interp):
            # Find the intervals for xi and yi
            for i in range(len(x) - 1):
                if x[i] <= xi <= x[i + 1]:
                    for j in range(len(y) - 1):
                        if y[j] <= yi <= y[j + 1]:
                            # Bilinear interpolation
                            tx = (xi - x[i]) / (x[i + 1] - x[i])
                            ty = (yi - y[j]) / (y[j + 1] - y[j])

                            # Interpolate along x for both y[j] and y[j+1]
                            z_xj   = z[i][j]   + tx * (z[i + 1][j]   - z[i][j])
                            z_xj1  = z[i][j + 1] + tx * (z[i + 1][j + 1] - z[i][j + 1])

                            # Interpolate along y
                            zi = z_xj + ty * (z_xj1 - z_xj)
                            z_interp.append(zi)
                            break
                    break
        return z_interp

